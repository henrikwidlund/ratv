//! Generates `crates/ratv-mrp/src/generated.rs` from `crates/ratv-mrp/proto`.
//!
//! Run from the workspace root: `cargo run -p proto-gen`.
//!
//! The MRP protos add messages to `ProtocolMessage` with proto2 extensions,
//! which prost does not support. Each `extend ProtocolMessage { ... }` block
//! is moved into `ProtocolMessage` as a normal field with the same number,
//! so the wire format is unchanged.
//!
//! It also writes `src/payloads.rs` with the field number and message type of
//! every moved message.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

const PROTOCOL_MESSAGE: &str = "protocol/ProtocolMessage.proto";
const PROTOCOL_IMPORT: &str = "import \"protocol/ProtocolMessage.proto\";";

fn main() {
    let root = Path::new("crates/ratv-mrp");
    let src = root.join("proto");
    let tmp = PathBuf::from("target/proto-gen");
    let _ = fs::remove_dir_all(&tmp);

    let mut files = Vec::new();
    collect(&src, &src, &mut files);
    files.sort();

    let mut fields = String::new();
    let mut imports = String::new();
    for rel in &files {
        let text = fs::read_to_string(src.join(rel)).expect("read proto");
        let out = if rel == PROTOCOL_MESSAGE {
            text
        } else {
            let (rest, extensions) = take_extensions(&text);
            if !extensions.is_empty() {
                fields.push_str(&extensions);
                let _ = writeln!(imports, "import \"{rel}\";");
            }
            rest.replace(PROTOCOL_IMPORT, "")
        };
        let dst = tmp.join(rel);
        fs::create_dir_all(dst.parent().expect("parent")).expect("create dir");
        fs::write(dst, out).expect("write proto");
    }

    let pm_path = tmp.join(PROTOCOL_MESSAGE);
    let pm = fs::read_to_string(&pm_path).expect("read ProtocolMessage");
    let pm = pm
        .lines()
        .filter(|l| !l.trim_start().starts_with("extensions "))
        .collect::<Vec<_>>()
        .join("\n");
    let pm = pm.replacen(
        "syntax = \"proto2\";",
        &format!("syntax = \"proto2\";\n\n{imports}"),
        1,
    );
    let marker = "message ProtocolMessage {";
    let pm = pm.replacen(marker, &format!("{marker}\n{fields}"), 1);
    fs::write(&pm_path, pm).expect("write ProtocolMessage");

    let fds = protox::compile(&files, [&tmp]).expect("compile protos");
    let out_dir = tmp.join("out");
    fs::create_dir_all(&out_dir).expect("create out dir");
    prost_build::Config::new()
        .out_dir(&out_dir)
        .bytes(["."])
        .compile_fds(fds)
        .expect("generate Rust");
    let generated = fs::read_to_string(out_dir.join("_.rs")).expect("read generated");
    let header = "// Generated by `cargo run -p proto-gen`. Do not edit.\n\n";
    fs::write(
        root.join("src/generated.rs"),
        format!("{header}{generated}"),
    )
    .expect("write generated");

    let types = message_types(
        &fs::read_to_string(src.join(PROTOCOL_MESSAGE)).expect("read ProtocolMessage"),
    );
    let mut table = String::from(header);
    for line in fields.lines() {
        // `optional TypeName fieldName = 6;`
        let parts: Vec<&str> = line.split_whitespace().collect();
        let (ty, tag) = (parts[1], parts[4].trim_end_matches(';'));
        if ty.starts_with(char::is_lowercase) {
            // Scalar field, not a message.
            continue;
        }
        let kind = types
            .iter()
            .find(|(name, _)| {
                name.eq_ignore_ascii_case(ty)
                    || ty
                        .strip_suffix("Message")
                        .is_some_and(|t| name.eq_ignore_ascii_case(t))
            })
            .map_or(0, |(_, v)| *v);
        let _ = writeln!(table, "payload!({}, {tag}, {kind});", rust_name(ty));
    }
    fs::write(root.join("src/payloads.rs"), table).expect("write payloads");
    println!("generated {} files", files.len());
}

fn collect(base: &Path, dir: &Path, out: &mut Vec<String>) {
    for entry in fs::read_dir(dir).expect("read dir") {
        let path = entry.expect("entry").path();
        if path.is_dir() {
            collect(base, &path, out);
        } else if path.extension().is_some_and(|e| e == "proto") {
            let rel = path.strip_prefix(base).expect("relative");
            out.push(rel.to_string_lossy().replace('\\', "/"));
        }
    }
}

/// Removes `extend ProtocolMessage { ... }` blocks. Returns the rest and the fields.
fn take_extensions(text: &str) -> (String, String) {
    let mut rest = String::with_capacity(text.len());
    let mut fields = String::new();
    let mut remaining = text;
    while let Some(start) = remaining.find("extend ProtocolMessage") {
        rest.push_str(&remaining[..start]);
        let open = start + remaining[start..].find('{').expect("extend block opens");
        let close = open + remaining[open..].find('}').expect("extend block closes");
        for line in remaining[open + 1..close].lines() {
            let line = line.trim();
            if !line.is_empty() && !line.starts_with("//") {
                let _ = writeln!(fields, "  {line}");
            }
        }
        remaining = &remaining[close + 1..];
    }
    rest.push_str(remaining);
    (rest, fields)
}

/// Reads `enum Type` of `ProtocolMessage` as (`PascalCaseName`, value).
fn message_types(text: &str) -> Vec<(String, i32)> {
    let start = text.find("enum Type {").expect("enum Type");
    let end = start + text[start..].find('}').expect("enum end");
    text[start..end]
        .lines()
        .filter_map(|l| {
            let l = l.split("//").next()?.trim();
            let (name, value) = l.trim_end_matches(';').split_once('=')?;
            let pascal: String = name
                .trim()
                .split('_')
                .map(|w| {
                    let mut c = w.chars();
                    c.next().map_or(String::new(), |f| {
                        f.to_string() + &c.as_str().to_lowercase()
                    })
                })
                .collect();
            Some((pascal, value.trim().parse().ok()?))
        })
        .collect()
}

/// Type name as prost writes it: runs of capitals become one capital word,
/// for example `RegisterHIDDeviceMessage` -> `RegisterHidDeviceMessage`.
fn rust_name(proto: &str) -> String {
    let chars: Vec<char> = proto.chars().collect();
    let mut out = String::with_capacity(proto.len());
    for (i, &c) in chars.iter().enumerate() {
        let prev_upper = i > 0 && chars[i - 1].is_uppercase();
        let next_lower = chars.get(i + 1).is_some_and(|n| n.is_lowercase());
        if c.is_uppercase() && prev_upper && !next_lower {
            out.extend(c.to_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}
